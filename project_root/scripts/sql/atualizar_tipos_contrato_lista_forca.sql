-- 3) aplica o tipo nos professores já cadastrados
UPDATE harpiadb_professores_professor p
   SET tipo_contrato_id = tc.id
  FROM tmp_lista_forca_tipo s
  JOIN harpiadb_professores_tipo_contrato tc ON tc.nome = s.tipo_nome
 WHERE p.id_funcional = s.id_funcional
   AND p.tipo_contrato_id IS DISTINCT FROM tc.id;

-- 4) remove tipos antigos que não são mais permitidos E não têm professor vinculado
DELETE FROM harpiadb_professores_tipo_contrato tc
 WHERE tc.nome NOT IN (SELECT nome FROM (VALUES

    ('PROF FAETEC ENS SUP 40H'),
    ('PROFESSOR FAETEC I 20 H'),
    ('PROFESSOR FAETEC I 40 H'),
    ('PROFESSOR FAETEC II - 40 H/ QD SUPL'),
    ('PROFESSOR INSPETOR ESCOLAR L9146''2020'),
    ('PROFESSOR SUPERVISOR EDUCACIONAL L9146''2020'),
    ('SUPERVISOR EDUCACIONAL'),
    ('TÉCNICO SUPERIOR'),
    ('ORIENTADOR EDUCACIONAL'),
    ('PROFESSOR CEDIDO')
 ) AS ok(nome))
   AND NOT EXISTS (SELECT 1 FROM harpiadb_professores_professor p WHERE p.tipo_contrato_id = tc.id);

-- 5) RELATÓRIO: professores cadastrados que continuam num tipo fora da lista
--    (cargo não permitido no PDF ou ID funcional ausente da lista). Decida caso a caso.
SELECT p.id_funcional, p.rh_nome, tc.nome AS tipo_atual
  FROM harpiadb_professores_professor p
  JOIN harpiadb_professores_tipo_contrato tc ON tc.id = p.tipo_contrato_id
 WHERE tc.nome NOT IN (SELECT DISTINCT tipo_nome FROM tmp_lista_forca_tipo)
 ORDER BY tc.nome, p.rh_nome;

