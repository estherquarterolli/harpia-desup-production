-- 1) cria / ajusta os tipos de contrato permitidos
DO $$
DECLARE r record; v_horas int;
BEGIN
    FOR r IN SELECT * FROM (VALUES
    ('PROF FAETEC ENS SUP 40H', 40),
    ('PROFESSOR FAETEC I 20 H', 20),
    ('PROFESSOR FAETEC I 40 H', 40),
    ('PROFESSOR FAETEC II - 40 H/ QD SUPL', 40),
    ('PROFESSOR INSPETOR ESCOLAR L9146''2020', 40),
    ('PROFESSOR SUPERVISOR EDUCACIONAL L9146''2020', 40),
    ('SUPERVISOR EDUCACIONAL', 40),
    ('TÉCNICO SUPERIOR', 40),
    ('ORIENTADOR EDUCACIONAL', 40),
    ('PROFESSOR CEDIDO', 40)
    ) AS t(nome, horas) LOOP
        v_horas := r.horas;
        IF EXISTS (SELECT 1 FROM harpiadb_professores_tipo_contrato WHERE nome = r.nome) THEN
            UPDATE harpiadb_professores_tipo_contrato
               SET regime_trabalho = v_horas || 'h',
                   max_total_hours = v_horas,
                   max_class_hours = v_horas / 2,
                   dias_presenca_obrigatorios = CASE WHEN v_horas >= 40 THEN 3 ELSE 2 END,
                   max_classes = CASE WHEN v_horas >= 40 THEN 6 ELSE 4 END
             WHERE nome = r.nome;
        ELSE
            INSERT INTO harpiadb_professores_tipo_contrato
                (nome, categoria, regime_trabalho, dias_presenca_obrigatorios, max_class_hours, max_total_hours, max_classes)
            VALUES (r.nome, 'EFETIVO', v_horas || 'h', CASE WHEN v_horas >= 40 THEN 3 ELSE 2 END,
                    v_horas / 2, v_horas, CASE WHEN v_horas >= 40 THEN 6 ELSE 4 END);
        END IF;
    END LOOP;
END $$;

