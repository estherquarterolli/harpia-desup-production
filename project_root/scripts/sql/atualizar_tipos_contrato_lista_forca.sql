--
-- Regras:
--   * Passam a existir SOMENTE estes tipos de contrato:
--       - PROF FAETEC ENS SUP 40H
--       - PROFESSOR FAETEC I 20 H
--       - PROFESSOR FAETEC I 40 H
--       - PROFESSOR FAETEC II - 40 H/ QD SUPL
--       - PROFESSOR INSPETOR ESCOLAR L9146'2020
--       - PROFESSOR SUPERVISOR EDUCACIONAL L9146'2020
--       - SUPERVISOR EDUCACIONAL
--       - TÉCNICO SUPERIOR
--       - ORIENTADOR EDUCACIONAL
--       - PROFESSOR CEDIDO
--   * Regime 20h  -> alocação máxima em sala de 10h.
--     Regime 40h  -> alocação máxima em sala de 20h.
--     (tipos sem carga explícita no nome — supervisor, técnico, orientador, inspetor, cedido —
--      foram tratados como 40h/20h; para quem tem carga diferente, marque "Professor com carga
--      diferente" no cadastro do professor e informe a carga)
--   * Cada professor (por ID funcional) recebe o tipo da linha do PDF. Quem aparece em mais de um
--     vínculo (ex.: 20h + 40h) fica com o de maior carga.
--   * Só entram no mapeamento as linhas do PDF cujo cargo está na lista acima (935 IDs funcionais).
--     Cargos fora da lista (agente administrativo, inspetor de alunos, instrutor, contrato temporário
--     "PROFESSOR I ... DEC 49208" etc.) NÃO são alterados — veja o relatório do bloco 5.
--   * A matrícula deixa de ser obrigatória (coluna passa a aceitar NULL; matrículas provisórias
--     "SEM-MATRICULA-..." viram NULL).
--
-- Seguro para rodar mais de uma vez. Faça backup antes. Rode tudo de uma vez no SQL Editor.

