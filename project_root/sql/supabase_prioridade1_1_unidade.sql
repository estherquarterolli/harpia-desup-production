CREATE TABLE IF NOT EXISTS public.harpiadb_nucleo_atividade_estagio_supervisao (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    tipo character varying(30) NOT NULL DEFAULT 'SUPERVISAO_ESTAGIO',
    semestre character varying(10) NOT NULL,
    num_estudantes smallint NOT NULL DEFAULT 1,
    carga_horaria_semanal numeric(5, 2) NOT NULL DEFAULT 0.00,
    carga_reducao_horas numeric(5, 2) NOT NULL DEFAULT 0.00,
    data_inicio date NOT NULL,
    data_fim date NULL,
    observacoes text NOT NULL DEFAULT '',
    criado_em timestamp with time zone NOT NULL DEFAULT now(),
    atualizado_em timestamp with time zone NOT NULL DEFAULT now(),
    criado_por_id bigint NULL,
    curso_id bigint NULL,
    professor_id bigint NOT NULL,
    unidade_id bigint NOT NULL,
    CONSTRAINT harpiadb_nucleo_atividade_estagio_supervisao_pkey PRIMARY KEY (id),
    CONSTRAINT harpiadb_nucleo_ativ_criado_por_id_fk
        FOREIGN KEY (criado_por_id) REFERENCES public.harpiadb_contas_usuario(id)
        ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT harpiadb_nucleo_ativ_curso_id_fk
        FOREIGN KEY (curso_id) REFERENCES public.harpiadb_cursos_curso_unidade(id)
        ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT harpiadb_nucleo_ativ_professor_id_fk
        FOREIGN KEY (professor_id) REFERENCES public.harpiadb_docentes_professor(id)
        ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT harpiadb_nucleo_ativ_unidade_id_fk
        FOREIGN KEY (unidade_id) REFERENCES public.harpiadb_nucleo_unidade(id)
        ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT harpia_estagio_data_valida
        CHECK (data_fim IS NULL OR data_fim >= data_inicio),
    CONSTRAINT harpia_estagio_ch_nao_neg
        CHECK (carga_horaria_semanal >= 0),
    CONSTRAINT harpia_estagio_red_nao_neg
        CHECK (carga_reducao_horas >= 0),
    CONSTRAINT harpia_estagio_num_estudantes_pos
        CHECK (num_estudantes >= 1 AND num_estudantes <= 200)
);

