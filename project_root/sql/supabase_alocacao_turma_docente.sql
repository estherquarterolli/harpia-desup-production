-- Equivale às migrations:
--   allocations.0004_alocacao_turma_docente_carencia_rat
--   courses.0010_matrixcomponent_quantidade_turmas
--   allocations.0005_migrar_docente_componente_para_alocacao_turma  (cópia dos dados)
--   courses.0011_remove_matrixcomponent_docente
--
-- Use ESTE script OU "python manage.py migrate" — não os dois. Se o deploy já rodou
-- "migrate", este script apenas confirma o estado (é idempotente) e não altera nada.
--
-- SEGURANÇA DOS DADOS: o campo harpiadb_cursos_componente_matriz.docente_id só é
-- removido depois de copiado para a nova tabela. Se algum componente com docente
-- não puder ser mapeado (matriz sem unidade ou sem vínculo em "Cursos na Unidade"),
-- o script ABORTA com erro e nada é alterado (tudo roda numa única transação).
-- Recomenda-se fazer backup antes de executar.

BEGIN;

