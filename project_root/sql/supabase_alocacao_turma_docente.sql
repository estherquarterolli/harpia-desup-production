-- 1) Quantidade de turmas do componente (padrão: 1) ------------------------------
ALTER TABLE public.harpiadb_cursos_componente_matriz
    ADD COLUMN IF NOT EXISTS quantidade_turmas smallint NOT NULL DEFAULT 1
        CHECK (quantidade_turmas >= 0);
ALTER TABLE public.harpiadb_cursos_componente_matriz
    ALTER COLUMN quantidade_turmas DROP DEFAULT;

-- 2) Novas tabelas ---------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.harpiadb_alocacoes_alocacao_turma_docente (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    carga_horaria_contabilizada numeric(6, 2) NOT NULL,
    compartilhado boolean NOT NULL,
    criado_em timestamp with time zone NOT NULL,
    atualizado_em timestamp with time zone NOT NULL,
    alocacao_curricular_id bigint NOT NULL
        REFERENCES public.harpiadb_alocacoes_alocacao_curricular (id) ON DELETE CASCADE,
    componente_matriz_id bigint NOT NULL
        REFERENCES public.harpiadb_cursos_componente_matriz (id) ON DELETE RESTRICT,
    docente_id bigint NULL
        REFERENCES public.harpiadb_professores_professor (id) ON DELETE RESTRICT,
    turma_id bigint NULL
        REFERENCES public.harpiadb_cursos_turma (id) ON DELETE RESTRICT,
    CONSTRAINT harpia_alocturmadocente_unica
        UNIQUE (alocacao_curricular_id, componente_matriz_id, turma_id, docente_id)
);
DROP INDEX IF EXISTS public.harpia_alocturmadocente_unica_sem_turma;
CREATE INDEX IF NOT EXISTS harpia_alocturmadocente_aloc_idx
    ON public.harpiadb_alocacoes_alocacao_turma_docente (alocacao_curricular_id);
CREATE INDEX IF NOT EXISTS harpia_alocturmadocente_comp_idx
    ON public.harpiadb_alocacoes_alocacao_turma_docente (componente_matriz_id);
CREATE INDEX IF NOT EXISTS harpia_alocturmadocente_docente_idx
    ON public.harpiadb_alocacoes_alocacao_turma_docente (docente_id);
CREATE INDEX IF NOT EXISTS harpia_alocturmadocente_turma_idx
    ON public.harpiadb_alocacoes_alocacao_turma_docente (turma_id);

CREATE TABLE IF NOT EXISTS public.harpiadb_alocacoes_carencia (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    status varchar(20) NOT NULL,
    justificativa_unidade text NOT NULL,
    parecer_desup text NOT NULL,
    criado_em timestamp with time zone NOT NULL,
    atualizado_em timestamp with time zone NOT NULL,
    alocacao_turma_docente_id bigint NOT NULL UNIQUE
        REFERENCES public.harpiadb_alocacoes_alocacao_turma_docente (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.harpiadb_alocacoes_solicitacao_rat (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    carga_horaria_solicitada numeric(6, 2) NOT NULL,
    status varchar(20) NOT NULL,
    data_solicitacao timestamp with time zone NOT NULL,
    data_avaliacao timestamp with time zone NULL,
    motivo_parecer text NOT NULL,
    avaliado_por_id bigint NULL
        REFERENCES public.harpiadb_contas_usuario (id) ON DELETE RESTRICT,
    carencia_id bigint NOT NULL
        REFERENCES public.harpiadb_alocacoes_carencia (id) ON DELETE CASCADE,
    professor_id bigint NOT NULL
        REFERENCES public.harpiadb_professores_professor (id) ON DELETE RESTRICT,
    solicitado_por_id bigint NOT NULL
        REFERENCES public.harpiadb_contas_usuario (id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS harpia_rat_carencia_idx
    ON public.harpiadb_alocacoes_solicitacao_rat (carencia_id);
CREATE INDEX IF NOT EXISTS harpia_rat_professor_idx
    ON public.harpiadb_alocacoes_solicitacao_rat (professor_id);
CREATE INDEX IF NOT EXISTS harpia_rat_solicitado_idx
    ON public.harpiadb_alocacoes_solicitacao_rat (solicitado_por_id);
CREATE INDEX IF NOT EXISTS harpia_rat_avaliado_idx
    ON public.harpiadb_alocacoes_solicitacao_rat (avaliado_por_id);

-- 3) Cópia dos dados e remoção do campo antigo (só se ele ainda existir) ---------
DO $$
DECLARE
    v_semestre text;
    v_nao_mapeados integer;
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'harpiadb_cursos_componente_matriz'
          AND column_name = 'docente_id'
    ) THEN
        RAISE NOTICE 'docente_id já foi removido; nada a copiar.';
        RETURN;
    END IF;

    -- Mesmo critério da aplicação: o consolidado é sempre do semestre corrente.
    v_semestre := to_char(now() AT TIME ZONE 'America/Sao_Paulo', 'YYYY') || '.' ||
        CASE WHEN extract(month FROM now() AT TIME ZONE 'America/Sao_Paulo') <= 6
             THEN '1' ELSE '2' END;

    CREATE TEMP TABLE _harpia_mapa ON COMMIT DROP AS
    SELECT cm.id AS componente_id,
           cm.docente_id,
           cm.carga_horaria,
           cm.compartilhado,
           COALESCE(m.turno, 'M') AS turno,
           cu.id AS course_unit_id,
           mapa.unidade_id
    FROM public.harpiadb_cursos_componente_matriz cm
    JOIN public.harpiadb_cursos_matriz_curricular m ON m.id = cm.matriz_id
    JOIN public.harpiadb_professores_professor p ON p.id = cm.docente_id
    -- Unidade: a principal do docente se pertencer à matriz; senão, a de menor id.
    LEFT JOIN LATERAL (
        SELECT COALESCE(
            (SELECT mu.unidade_id FROM public.harpiadb_cursos_matriz_unidades mu
              WHERE mu.curriculummatrix_id = m.id AND mu.unidade_id = p.unidade_principal_id),
            (SELECT min(mu.unidade_id) FROM public.harpiadb_cursos_matriz_unidades mu
              WHERE mu.curriculummatrix_id = m.id)
        ) AS unidade_id
    ) mapa ON TRUE
    LEFT JOIN public.harpiadb_cursos_curso_unidade cu
           ON cu.curso_id = m.curso_id AND cu.unidade_id = mapa.unidade_id
    WHERE cm.docente_id IS NOT NULL;

    SELECT count(*) INTO v_nao_mapeados FROM _harpia_mapa WHERE course_unit_id IS NULL;
    IF v_nao_mapeados > 0 THEN
        RAISE EXCEPTION
            '% componente(s) com docente não puderam ser mapeados (matriz sem unidade ou sem vínculo em Cursos na Unidade). Nada foi alterado.',
            v_nao_mapeados;
    END IF;

    INSERT INTO public.harpiadb_alocacoes_alocacao_curricular
        (semestre, turno, status, sei_numero, data_criacao, data_ultimo_ajuste, curso_id, unidade_id)
    SELECT DISTINCT v_semestre, turno, 'Rascunho', NULL, now(), now(), course_unit_id, unidade_id
    FROM _harpia_mapa
    ON CONFLICT DO NOTHING;

    INSERT INTO public.harpiadb_alocacoes_alocacao_turma_docente
        (carga_horaria_contabilizada, compartilhado, criado_em, atualizado_em,
         alocacao_curricular_id, componente_matriz_id, docente_id, turma_id)
    SELECT round(mp.carga_horaria / 20.0, 2), mp.compartilhado, now(), now(),
           ac.id, mp.componente_id, mp.docente_id, NULL
    FROM _harpia_mapa mp
    JOIN public.harpiadb_alocacoes_alocacao_curricular ac
      ON ac.curso_id = mp.course_unit_id AND ac.unidade_id = mp.unidade_id
     AND ac.semestre = v_semestre AND ac.turno = mp.turno
    ON CONFLICT DO NOTHING;

    ALTER TABLE public.harpiadb_cursos_componente_matriz DROP COLUMN docente_id;
END
$$;

